"""Generate the optional manual dashboard from the integration's single template.

Run: python3 scripts/generate_dashboard_example.py [--check]
Only the Python standard library is required.
"""
import argparse
import ast
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
COMPONENT = ROOT / 'custom_components/samsung_ehs_monitor'
HEADER = '''# Generated by scripts/generate_dashboard_example.py; edit the bundled template.
# Paste into a dedicated dashboard's Raw configuration editor.
# Entity IDs assume no area prefix; adjust them to match your entity registry.
# The integration-managed dashboard resolves entity IDs automatically.
'''


def generate():
    names = {'failure_log': 'Failure log', 'cycle_indoor': 'Indoor cycle raw hex',
             'cycle_outdoor': 'Outdoor cycle raw hex'}
    tree = ast.parse((COMPONENT / 'sensor.py').read_text())
    for node in ast.walk(tree):
        if (isinstance(node, ast.Tuple) and len(node.elts) >= 2
                and all(isinstance(item, ast.Constant) and isinstance(item.value, str)
                        for item in node.elts[:2])):
            key, name = (item.value for item in node.elts[:2])
            names[key] = name
    template = (COMPONENT / 'dashboard.yaml').read_text()

    def entity(match):
        key = match[2]
        if key not in names and not key.startswith('fsv_'):
            raise ValueError(f'No sensor name for template key: {key}')
        slug = re.sub(r'[^a-z0-9]+', '_', names.get(key, key).lower()).strip('_')
        return f'{match[1]}sensor.samsung_ehs_monitor_{slug}'

    rendered = re.sub(r'((?:\bentity|\breturn_entity|\bdischarge_entity|\bpump_entity): )([a-zA-Z0-9_]+)', entity, template)
    return HEADER + rendered.replace('__FAILURE_LOG_ENTITY__', 'sensor.samsung_ehs_monitor_failure_log')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'dashboard_example.yaml'
    rendered = generate()
    if args.check:
        if output.read_text() != rendered:
            raise SystemExit('dashboard_example.yaml is out of date; run this script without --check')
    else:
        output.write_text(rendered)
